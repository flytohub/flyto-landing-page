import { execFileSync } from 'node:child_process';
import { createHash } from 'node:crypto';
import { existsSync, mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import ts from 'typescript';
import { escapeMarkdownCell } from './content-safety.mjs';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const outputDir = path.join(root, 'docs', 'reference');
const generatedMarker = '<!-- Generated by scripts/generate-documentation-reference.mjs; do not edit. -->';
const checkMode = process.argv.includes('--check');
const sourceExtensions = new Set(['.ts', '.tsx', '.js', '.jsx', '.mjs', '.cjs']);
const maxDeclarationsPerPage = 260;

function trackedFiles() {
  return execFileSync('git', ['-C', root, 'ls-files', '--cached', '--others', '--exclude-standard'], { encoding: 'utf8' })
    .split(/\r?\n/)
    .filter(Boolean)
    .sort();
}

function read(relativePath) {
  return readFileSync(path.join(root, relativePath), 'utf8');
}

function sourceKind(relativePath) {
  if (relativePath.endsWith('.tsx') || relativePath.endsWith('.jsx')) return ts.ScriptKind.TSX;
  if (relativePath.endsWith('.ts')) return ts.ScriptKind.TS;
  return ts.ScriptKind.JS;
}

function lineOf(sourceFile, node) {
  return sourceFile.getLineAndCharacterOfPosition(node.getStart(sourceFile)).line + 1;
}

function declarationName(node, sourceFile) {
  if (node.name?.getText) return node.name.getText(sourceFile);
  return 'default';
}

function firstComment(node, sourceFile) {
  const comments = ts.getJSDocCommentsAndTags(node)
    .map((entry) => entry.comment)
    .filter((value) => typeof value === 'string')
    .map((value) => value.replace(/\s+/g, ' ').trim())
    .filter(Boolean);
  return comments[0] ?? '';
}

function humanize(value) {
  return String(value)
    .replace(/^use(?=[A-Z])/, '')
    .replace(/([a-z0-9])([A-Z])/g, '$1 $2')
    .replace(/[_-]+/g, ' ')
    .replace(/\s+/g, ' ')
    .trim()
    .toLowerCase();
}

function responsibility(kind, name, comment) {
  if (comment) return comment;
  const subject = humanize(name.replace(/^.*\./, '')) || 'source contract';
  if (name === 'generateMetadata') return 'Builds canonical, social, and locale-aware metadata for the route.';
  if (name === 'generateStaticParams') return 'Enumerates statically generated route parameters.';
  if (kind === 'constructor') return `Initializes the ${humanize(name.replace(/\.constructor$/, ''))} instance.`;
  if (kind === 'getter') return `Reads ${subject}.`;
  if (kind === 'setter') return `Updates ${subject}.`;
  if (kind === 'method contract') return `Defines the callable ${subject} contract.`;
  if (kind === 'component') return `Renders the ${subject} interface.`;
  if (kind === 'interface' || kind === 'type' || kind === 'enum') return `Defines the ${subject} data contract.`;
  if (kind === 'class') return `Implements the ${subject} behavior.`;
  if (kind === 'constant') return `Defines the ${subject} source-of-truth value.`;
  if (/^(get|read|list|find|load|resolve|search)/i.test(name)) return `Retrieves ${subject}.`;
  if (/^(build|create|generate|make|render)/i.test(name)) return `Builds ${subject}.`;
  if (/^(check|audit|validate|verify|is|has)/i.test(name)) return `Validates ${subject}.`;
  if (/^(normalize|format|parse|decode|encode|convert)/i.test(name)) return `Transforms ${subject}.`;
  return `Implements ${subject}.`;
}

function signature(node, sourceFile, name) {
  if (ts.isFunctionDeclaration(node) || ts.isMethodDeclaration(node) || ts.isMethodSignature(node)
    || ts.isConstructorDeclaration(node) || ts.isGetAccessorDeclaration(node) || ts.isSetAccessorDeclaration(node)) {
    const params = node.parameters.map((param) => param.name.getText(sourceFile)).join(', ');
    return `${name}(${params})`;
  }
  if ((ts.isVariableDeclaration(node) || ts.isPropertyDeclaration(node))
    && node.initializer && (ts.isArrowFunction(node.initializer) || ts.isFunctionExpression(node.initializer))) {
    const params = node.initializer.parameters.map((param) => param.name.getText(sourceFile)).join(', ');
    return `${name}(${params})`;
  }
  if (ts.isPropertySignature(node) && node.type && ts.isFunctionTypeNode(node.type)) {
    const params = node.type.parameters.map((param) => param.name.getText(sourceFile)).join(', ');
    return `${name}(${params})`;
  }
  return name;
}

function isTopLevelVariable(node) {
  return ts.isVariableDeclaration(node)
    && ts.isVariableDeclarationList(node.parent)
    && ts.isVariableStatement(node.parent.parent)
    && ts.isSourceFile(node.parent.parent.parent);
}

function declarationsFor(relativePath) {
  const text = read(relativePath);
  const sourceFile = ts.createSourceFile(relativePath, text, ts.ScriptTarget.Latest, true, sourceKind(relativePath));
  const declarations = [];

  function add(node, kind, forcedName = '') {
    const name = forcedName || declarationName(node, sourceFile);
    declarations.push({
      path: relativePath,
      line: lineOf(sourceFile, node),
      kind,
      name,
      signature: signature(node, sourceFile, name),
      responsibility: responsibility(kind, name, firstComment(node, sourceFile)),
    });
  }

  function visit(node, parentOwner = '') {
    let childOwner = parentOwner;
    if (ts.isFunctionDeclaration(node)) {
      const name = declarationName(node, sourceFile);
      add(node, /^[A-Z]/.test(name) && relativePath.endsWith('x') ? 'component' : 'function', name);
    } else if (ts.isClassDeclaration(node)) {
      add(node, 'class');
      childOwner = declarationName(node, sourceFile);
    } else if (ts.isInterfaceDeclaration(node)) {
      add(node, 'interface');
      childOwner = declarationName(node, sourceFile);
    } else if (ts.isTypeAliasDeclaration(node)) {
      add(node, 'type');
    } else if (ts.isEnumDeclaration(node)) {
      add(node, 'enum');
    } else if (ts.isConstructorDeclaration(node)) {
      add(node, 'constructor', parentOwner ? `${parentOwner}.constructor` : 'constructor');
    } else if (ts.isMethodDeclaration(node)) {
      const method = declarationName(node, sourceFile);
      add(node, 'method', parentOwner ? `${parentOwner}.${method}` : method);
    } else if (ts.isGetAccessorDeclaration(node) || ts.isSetAccessorDeclaration(node)) {
      const accessor = declarationName(node, sourceFile);
      add(node, ts.isGetAccessorDeclaration(node) ? 'getter' : 'setter', parentOwner ? `${parentOwner}.${accessor}` : accessor);
    } else if (ts.isMethodSignature(node)) {
      const method = declarationName(node, sourceFile);
      add(node, 'method contract', parentOwner ? `${parentOwner}.${method}` : method);
    } else if (ts.isPropertyDeclaration(node) && node.initializer
      && (ts.isArrowFunction(node.initializer) || ts.isFunctionExpression(node.initializer))) {
      const property = declarationName(node, sourceFile);
      add(node, 'method', parentOwner ? `${parentOwner}.${property}` : property);
    } else if (ts.isPropertySignature(node) && node.type && ts.isFunctionTypeNode(node.type)) {
      const property = declarationName(node, sourceFile);
      add(node, 'method contract', parentOwner ? `${parentOwner}.${property}` : property);
    } else if (ts.isVariableDeclaration(node)) {
      const name = declarationName(node, sourceFile);
      const callable = node.initializer && (ts.isArrowFunction(node.initializer) || ts.isFunctionExpression(node.initializer));
      if (callable || isTopLevelVariable(node)) {
        add(node, callable && /^[A-Z]/.test(name) && relativePath.endsWith('x') ? 'component' : callable ? 'function' : 'constant', name);
      }
    }
    ts.forEachChild(node, (child) => visit(child, childOwner));
  }

  visit(sourceFile);
  return declarations;
}

function areaFor(relativePath) {
  if (relativePath.startsWith('app/')) return 'app';
  if (relativePath.startsWith('components/')) return 'components';
  if (relativePath.startsWith('lib/')) return 'lib';
  if (relativePath.startsWith('scripts/')) return 'scripts';
  return 'runtime';
}

function title(value) {
  return value.replace(/(^|[-_ ])([a-z])/g, (_, prefix, letter) => `${prefix}${letter.toUpperCase()}`);
}

function escapeCell(value) {
  return escapeMarkdownCell(value);
}

function sourceLink(relativePath, line) {
  const encoded = relativePath.split('/').map(encodeURIComponent).join('/');
  return `[${relativePath}:${line}](../../${encoded}#L${line})`;
}

function routeFromPage(relativePath) {
  const route = relativePath
    .replace(/^app\/\[locale\]\/?/, '')
    .replace(/\/page\.tsx$/, '')
    .replace(/^page\.tsx$/, '')
    .replace(/\[([^\]]+)\]/g, ':$1');
  return route ? `/${route}/` : '/';
}

function routeInventory(files) {
  return files
    .filter((file) => /^app\/\[locale\]\/(?:.*\/)?page\.tsx$/.test(file))
    .map((file) => {
      const text = read(file);
      return {
        route: routeFromPage(file),
        file,
        metadata: /export\s+(?:async\s+)?function\s+generateMetadata|export\s+const\s+metadata/.test(text),
        staticParams: /export\s+(?:async\s+)?function\s+generateStaticParams/.test(text),
        structuredData: /application\/ld\+json|schema\.org|['"]@type['"]/.test(text),
      };
    })
    .sort((a, b) => a.route.localeCompare(b.route));
}

function flattenKeys(value, prefix = '') {
  if (!value || typeof value !== 'object' || Array.isArray(value)) return prefix ? [prefix] : [];
  return Object.entries(value).flatMap(([key, child]) => flattenKeys(child, prefix ? `${prefix}.${key}` : key));
}

function envInventory(files) {
  const found = new Map();
  for (const file of files.filter((entry) => sourceExtensions.has(path.extname(entry)))) {
    const text = read(file);
    for (const match of text.matchAll(/process\.env\.([A-Z][A-Z0-9_]*)/g)) {
      if (!found.has(match[1])) found.set(match[1], new Set());
      found.get(match[1]).add(file);
    }
  }
  for (const file of ['.env.example', '.env.local.example'].filter((entry) => existsSync(path.join(root, entry)))) {
    for (const line of read(file).split(/\r?\n/)) {
      const match = line.match(/^([A-Z][A-Z0-9_]*)=/);
      if (!match) continue;
      if (!found.has(match[1])) found.set(match[1], new Set());
      found.get(match[1]).add(file);
    }
  }
  return [...found.entries()].map(([name, sources]) => ({ name, sources: [...sources].sort() })).sort((a, b) => a.name.localeCompare(b.name));
}

function workflowInventory(files) {
  return files.filter((file) => file.startsWith('.github/workflows/') && /\.ya?ml$/.test(file)).map((file) => {
    const text = read(file);
    return { file, name: text.match(/^name:\s*(.+)$/m)?.[1]?.trim() ?? path.basename(file), scheduled: /^\s*schedule:/m.test(text) };
  });
}

function whitepaperInventory(files) {
  return files.filter((file) => file.startsWith('content/whitepaper/') && file.endsWith('.md')).map((file) => ({
    file,
    title: read(file).match(/^#\s+(.+)$/m)?.[1]?.trim() ?? path.basename(file, '.md'),
  }));
}

function renderSourcePage(area, pageNumber, pageCount, rows) {
  const heading = `${title(area)} Source Reference${pageCount > 1 ? ` ${pageNumber}` : ''}`;
  const lines = [generatedMarker, '', `# ${heading}`, '', `Source-backed contracts for **${rows.length} declarations**.`, '', '| Kind | Declaration | Responsibility | Source |', '|---|---|---|---|'];
  for (const row of rows) {
    lines.push(`| ${row.kind} | \`${escapeCell(row.signature)}\` | ${escapeCell(row.responsibility)} | ${sourceLink(row.path, row.line)} |`);
  }
  return `${lines.join('\n')}\n`;
}

function buildOutputs(files) {
  const sourceFiles = files.filter((file) => sourceExtensions.has(path.extname(file)) && !file.endsWith('.d.ts'));
  const declarations = sourceFiles.flatMap(declarationsFor).sort((a, b) => a.path.localeCompare(b.path) || a.line - b.line || a.name.localeCompare(b.name));
  const routes = routeInventory(files);
  const env = envInventory(files);
  const workflows = workflowInventory(files);
  const whitepapers = whitepaperInventory(files);
  const packageJson = JSON.parse(read('package.json'));
  const locales = files.filter((file) => /^messages\/[a-z-]+\.json$/.test(file));
  const baselineKeys = flattenKeys(JSON.parse(read('messages/en.json'))).sort();
  const outputs = new Map();
  const sourcePages = [];

  for (const area of ['app', 'components', 'lib', 'scripts', 'runtime']) {
    const rows = declarations.filter((entry) => areaFor(entry.path) === area);
    if (!rows.length) continue;
    const chunks = Array.from({ length: Math.ceil(rows.length / maxDeclarationsPerPage) }, (_, index) => rows.slice(index * maxDeclarationsPerPage, (index + 1) * maxDeclarationsPerPage));
    chunks.forEach((chunk, index) => {
      const file = `source-${area}-${String(index + 1).padStart(2, '0')}.md`;
      outputs.set(file, renderSourcePage(area, index + 1, chunks.length, chunk));
      sourcePages.push({ area, file, declarations: chunk.length });
    });
  }

  const routeLines = [generatedMarker, '', '# Public Route Reference', '', `The App Router contains **${routes.length} page modules**. Each public route is emitted for **${locales.length} locales**; dynamic template and whitepaper routes expand from their source registries.`, '', '| Route | Metadata | Static params | Structured data | Source |', '|---|---|---|---|---|'];
  for (const route of routes) routeLines.push(`| \`${route.route}\` | ${route.metadata ? 'yes' : 'no'} | ${route.staticParams ? 'yes' : 'no'} | ${route.structuredData ? 'yes' : 'no'} | ${sourceLink(route.file, 1)} |`);
  outputs.set('routes.md', `${routeLines.join('\n')}\n`);

  const configLines = [generatedMarker, '', '# Runtime Configuration', '', `Source and example files reference **${env.length} environment variables**. Public \`NEXT_PUBLIC_*\` values configure the browser client; unprefixed values are local or CI-only operator inputs and must stay out of committed files.`, '', '| Variable | Sources |', '|---|---|'];
  for (const item of env) configLines.push(`| \`${item.name}\` | ${item.sources.map((source) => `\`${source}\``).join(', ')} |`);
  outputs.set('configuration.md', `${configLines.join('\n')}\n`);

  const automationLines = [generatedMarker, '', '# Automation Reference', '', `The repository exposes **${Object.keys(packageJson.scripts ?? {}).length} npm scripts** and **${workflows.length} GitHub workflows**.`, '', '## NPM Scripts', '', '| Script | Command |', '|---|---|'];
  for (const [name, command] of Object.entries(packageJson.scripts ?? {}).sort(([a], [b]) => a.localeCompare(b))) automationLines.push(`| \`${name}\` | \`${escapeCell(command)}\` |`);
  automationLines.push('', '## GitHub Workflows', '', '| Workflow | Scheduled | Source |', '|---|---|---|');
  for (const workflow of workflows) automationLines.push(`| ${escapeCell(workflow.name)} | ${workflow.scheduled ? 'yes' : 'no'} | [${workflow.file}](../../${workflow.file}) |`);
  outputs.set('automation.md', `${automationLines.join('\n')}\n`);

  const seoAssets = ['public/robots.txt', 'public/llms.txt', 'public/llms-full.txt', 'public/image-sitemap.xml', 'public/discovery-manifest.json', 'public/.well-known/security.txt', 'public/bimi/flyto2.svg'];
  const seoLines = [generatedMarker, '', '# SEO, AEO, GEO, And Locale Surfaces', '', `The landing site ships **${locales.length} locale catalogues** with **${baselineKeys.length} leaf message keys** in the English baseline. Route metadata, sitemap entries, discovery files, and AI-readable summaries are one release contract.`, '', '## Discovery Assets', '', '| Asset | Purpose |', '|---|---|'];
  const purpose = {
    'public/robots.txt': 'Search and AI crawler policy.',
    'public/llms.txt': 'Concise answer-engine index.',
    'public/llms-full.txt': 'Expanded citation-ready product index.',
    'public/image-sitemap.xml': 'Discoverable product imagery.',
    'public/discovery-manifest.json': 'Machine-readable discovery inventory.',
    'public/.well-known/security.txt': 'Responsible disclosure contact policy.',
    'public/bimi/flyto2.svg': 'BIMI-compatible brand mark.',
  };
  for (const asset of seoAssets) seoLines.push(`| [${asset}](../../${asset}) | ${purpose[asset]} |`);
  seoLines.push('', '## Locale Catalogues', '', ...locales.map((file) => `- [${file}](../../${file})`));
  outputs.set('seo-surfaces.md', `${seoLines.join('\n')}\n`);

  const contentLines = [generatedMarker, '', '# Long-Form Content Reference', '', `The public whitepaper library contains **${whitepapers.length} source documents**. Product claims in these files must remain consistent with current source repositories and generated inventories.`, '', '| Whitepaper | Source |', '|---|---|'];
  for (const item of whitepapers) contentLines.push(`| ${escapeCell(item.title)} | [${item.file}](../../${item.file}) |`);
  outputs.set('content.md', `${contentLines.join('\n')}\n`);

  const fingerprint = createHash('sha256');
  for (const file of [...sourceFiles, 'package.json', 'app/sitemap.ts', 'lib/public-route-pages.ts', ...whitepapers.map((item) => item.file)].sort()) fingerprint.update(file).update('\0').update(read(file)).update('\0');
  const indexLines = [generatedMarker, '', '# Flyto2 Landing Source Reference', '', 'This reference is generated from tracked source with the TypeScript compiler AST. It maps route modules, components, functions, methods, types, constants, scripts, configuration, content, and discovery assets back to maintained files.', '', 'The repository-owned coding route runs `npm_ci` as its first required check and `build_cf` as its last required check. Its governed required-check receipt must enumerate `npm_ci`, `typecheck`, `i18n`, `public_site_contract`, `verify`, and `build_cf` in that exact order, with all six checks passing.', '', `Inventory: **${declarations.length} declarations**, **${sourceFiles.length} source files**, **${routes.length} page modules**, **${locales.length} locales**, **${baselineKeys.length} baseline message keys**, **${env.length} environment variables**, **${Object.keys(packageJson.scripts ?? {}).length} npm scripts**, **${workflows.length} workflows**, and **${whitepapers.length} public whitepapers**.`, '', `Source fingerprint: \`${fingerprint.digest('hex')}\`.`, '', '## Source Areas', '', '| Area | Declarations | Reference |', '|---|---:|---|'];
  for (const page of sourcePages) indexLines.push(`| ${title(page.area)} | ${page.declarations} | [${page.file}](${page.file}) |`);
  indexLines.push('', '## Public Contracts', '', '- [Public routes](routes.md)', '- [SEO, AEO, GEO, and locale surfaces](seo-surfaces.md)', '- [Runtime configuration](configuration.md)', '- [Automation](automation.md)', '- [Long-form content](content.md)');
  outputs.set('README.md', `${indexLines.join('\n')}\n`);
  return outputs;
}

function verifyOrWrite(outputs) {
  const errors = [];
  for (const [file, expected] of outputs) {
    const absolute = path.join(outputDir, file);
    if (checkMode) {
      if (!existsSync(absolute)) errors.push(`missing generated reference: docs/reference/${file}`);
      else if (readFileSync(absolute, 'utf8') !== expected) errors.push(`stale generated reference: docs/reference/${file}`);
    } else {
      mkdirSync(path.dirname(absolute), { recursive: true });
      writeFileSync(absolute, expected);
    }
  }

  if (existsSync(outputDir)) {
    for (const file of readdirSync(outputDir).filter((entry) => entry.endsWith('.md'))) {
      const absolute = path.join(outputDir, file);
      if (!readFileSync(absolute, 'utf8').startsWith(generatedMarker) || outputs.has(file)) continue;
      if (checkMode) errors.push(`unexpected generated reference: docs/reference/${file}`);
      else rmSync(absolute);
    }
  }

  if (errors.length) {
    for (const error of errors) console.error(error);
    process.exit(1);
  }
  console.log(`landing documentation reference ${checkMode ? 'checked' : 'generated'}: ${outputs.size} pages`);
}

verifyOrWrite(buildOutputs(trackedFiles()));
