import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const contentDir = path.join(root, 'content', 'whitepaper');
const outputPath = path.join(root, 'lib', 'whitepaper-content.generated.ts');
const checkMode = process.argv.includes('--check');
const canonicalFiles = [
  'audit.md',
  'byo-integration.md',
  'code.md',
  'engine.md',
  'mssp-warroom.md',
  'security-surfaces.md',
  'supplement.md',
];

const bodies = Object.fromEntries(
  canonicalFiles.map((file) => [
    path.basename(file, '.md'),
    readFileSync(path.join(contentDir, file), 'utf8'),
  ]),
);

const output = `// Generated by scripts/generate-whitepaper-content.mjs; do not edit.\nexport const WHITEPAPER_BODY_BY_SLUG: Readonly<Record<string, string>> = ${JSON.stringify(bodies, null, 2)};\n`;

if (checkMode) {
  if (!existsSync(outputPath) || readFileSync(outputPath, 'utf8') !== output) {
    console.error('generated whitepaper content is stale; run npm run content:generate');
    process.exit(1);
  }
  console.log(`whitepaper content checked: ${canonicalFiles.length} documents`);
} else {
  writeFileSync(outputPath, output);
  console.log(`whitepaper content generated: ${canonicalFiles.length} documents`);
}
