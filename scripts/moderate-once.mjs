// Main
// ----------------------------------------------------------------

async function nukeMain() {
  console.log(`Mode: ${APPLY ? 'NUKE + APPLY — wiping forum_posts collection' : 'NUKE DRY-RUN — no deletes'}`);
  console.log('');

  const snap = await db.collection('forum_posts').get();
  console.log(`forum_posts contains ${snap.size} documents.`);

  // Tally subcollections we'll lose too, for transparency.
  let comments = 0;
  let reactions = 0;
  await Promise.all(
    snap.docs.map(async (d) => {
      const [c, r] = await Promise.all([
        d.ref.collection('comments').count().get(),
        d.ref.collection('reactions').count().get(),
      ]);
      comments += c.data().count;
      reactions += r.data().count;
    }),
  );
  console.log(`  + ${comments} comments`);
  console.log(`  + ${reactions} reactions`);
  console.log('');

  if (!APPLY) {
    console.log('Dry-run only. Re-run with --nuke --apply to PERMANENTLY DELETE everything above.');
    return;
  }

  console.log('Nuking…');
  await db.recursiveDelete(db.collection('forum_posts'));
  console.log(`Done. forum_posts is now empty.`);
}

async function main() {
  if (NUKE) return nukeMain();

  console.log(`Mode:        ${APPLY ? 'APPLY (DELETES from Firestore — irreversible)' : 'DRY-RUN (no deletes)'}`);
  console.log(`Batch size:  ${BATCH_SIZE}`);
  console.log(`Concurrency: ${CONCURRENCY}`);
  console.log(`Model:       ${MODEL}`);
  if (LIMIT) console.log(`Limit:       ${LIMIT}`);
  console.log('');

  let q = db.collection('forum_posts').orderBy('created_at');
  if (LIMIT) q = q.limit(LIMIT);
  const snap = await q.get();

  const all = snap.docs.map((d) => ({ id: d.id, ...d.data() }));

  console.log(`Loaded ${snap.size} posts; classifying all of them.`);

  const batches = [];
  for (let i = 0; i < all.length; i += BATCH_SIZE) {
    batches.push(all.slice(i, i + BATCH_SIZE));
  }
  console.log(`→ ${batches.length} batches\n`);

  const stats = { scanned: 0, doomed: 0, byCategory: {}, byLang: {} };
  const samples = [];
  const flagged = []; // full list of every classification flagged for deletion

  let idx = 0;
  async function worker() {
    while (idx < batches.length) {
      const myIdx = idx++;
      const batch = batches[myIdx];
      try {
        const results = await classifyBatch(batch);
        for (const r of results) {
          stats.scanned++;
          if (!r.hidden) continue;
          stats.doomed++;
          stats.byCategory[r.category] = (stats.byCategory[r.category] ?? 0) + 1;
          const post = batch.find((p) => p.id === r.id);
          if (post) {
            stats.byLang[post.lang] = (stats.byLang[post.lang] ?? 0) + 1;
            flagged.push({
              id: r.id,
              lang: post.lang,
              product: post.product,
              category: r.category,
              reason: r.reason,
              title: post.title,
            });
            if (samples.length < 30) {
              samples.push({
                id: r.id,
                lang: post.lang,
                category: r.category,
                reason: r.reason,
                title: post.title,
              });
            }
          }
          if (APPLY) {
            // Recursive delete — post doc + comments subcollection +
            // reactions subcollection. Firestore subcollections don't
            // cascade on parent delete.
            await db.recursiveDelete(db.collection('forum_posts').doc(r.id));
          }
        }
        const pct = (((myIdx + 1) / batches.length) * 100).toFixed(1);
        const verb = APPLY ? 'deleted' : 'would-delete';
        process.stdout.write(
          `\rBatch ${myIdx + 1}/${batches.length} (${pct}%) — ${verb} so far: ${stats.doomed}    `,
        );
      } catch (err) {
        console.error(`\nBatch ${myIdx} failed:`, err.message);
      }
    }
  }

  await Promise.all(Array.from({ length: CONCURRENCY }, worker));

  console.log('\n\n=== Summary ===');
  console.log(`Scanned: ${stats.scanned}`);
  const pct = stats.scanned ? ((stats.doomed / stats.scanned) * 100).toFixed(1) : '0.0';
  console.log(`${APPLY ? 'Deleted' : 'Would-delete'}: ${stats.doomed} (${pct}%)`);

  console.log('\nBy category:');
  for (const [k, v] of Object.entries(stats.byCategory).sort((a, b) => b[1] - a[1])) {
    console.log(`  ${k.padEnd(22)} ${v}`);
  }

  console.log('\nBy language:');
  for (const [k, v] of Object.entries(stats.byLang).sort((a, b) => b[1] - a[1])) {
    console.log(`  ${k.padEnd(4)} ${v}`);
  }

  console.log(`\nSample (first 30 of ${APPLY ? 'deleted' : 'would-delete'}):`);
  for (const s of samples) {
    const t = (s.title || '').replace(/\s+/g, ' ').slice(0, 70);
    console.log(`  [${s.lang}] ${s.category.padEnd(24)} ${t}`);
    console.log(`         ↳ ${s.reason}`);
  }

  // Write the full flagged list for review, regardless of mode.
  // In dry-run this is your "what would happen" report.
  // In apply mode this is your audit log of what got deleted.
  const out = APPLY ? 'moderation-applied.json' : 'moderation-dryrun.json';
  writeFileSync(out, JSON.stringify(flagged, null, 2));
  console.log(`\nFull list: ./${out} (${flagged.length} entries)`);

  if (!APPLY) {
    console.log('\nDry-run complete. Re-run with --apply to DELETE flagged posts.');
  } else {
    console.log('\nDeleted. Reload the forum to confirm.');
  }
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
